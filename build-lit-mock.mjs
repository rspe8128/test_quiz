/** correct at index a-1; 나머지 슬롯에 오답 배치 */
function buildChoices(right, w1, w2, w3, a) {
  const wrong = [w1, w2, w3];
  const slots = new Array(4);
  slots[a - 1] = right;
  let wi = 0;
  for (let i = 0; i < 4; i++) {
    if (slots[i] == null) slots[i] = wrong[wi++];
  }
  return { c: slots, a };
}

